from io import BytesIO
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle
)


def generate_pdf_report(history):

    buffer = BytesIO()

    document = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=40,
        leftMargin=40,
        topMargin=40,
        bottomMargin=40
    )

    styles = getSampleStyleSheet()
    elements = []

    # Prepare history data
    valid_history = []

    for record in history:
        subject, difficulty, question, score, date = record

        try:
            score = float(score)
        except (TypeError, ValueError):
            continue

        valid_history.append(
            (subject, difficulty, question, score, date)
        )

    if not valid_history:
        elements.append(
            Paragraph("No valid interview records available.", styles["Normal"])
        )
        document.build(elements)
        buffer.seek(0)
        return buffer.getvalue()

    # Calculate statistics
    total_attempts = len(valid_history)

    average_score = sum(
        record[3] for record in valid_history
    ) / total_attempts

    best_score = max(
        record[3] for record in valid_history
    )

    # Title
    elements.append(
        Paragraph(
            "InterviewPrep AI - Performance Report",
            styles["Title"]
        )
    )

    elements.append(Spacer(1, 20))

    elements.append(
        Paragraph("Performance Summary", styles["Heading2"])
    )

    summary_data = [
        ["Total Attempts", "Average Score", "Best Score"],
        [
            str(total_attempts),
            f"{average_score:.1f}%",
            f"{best_score:.0f}%"
        ]
    ]

    summary_table = Table(
        summary_data,
        colWidths=[160, 160, 160]
    )

    summary_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1E3A8A")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("BACKGROUND", (0, 1), (-1, 1), colors.HexColor("#EEF2FF")),
        ("TEXTCOLOR", (0, 1), (-1, 1), colors.HexColor("#172554")),
        ("ALIGN", (0, 0), (-1, -1), "CENTER"),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
        ("PADDING", (0, 0), (-1, -1), 10)
    ]))

    elements.append(summary_table)
    elements.append(Spacer(1, 25))

    # Subject-wise performance
    elements.append(
        Paragraph("Subject-wise Performance", styles["Heading2"])
    )

    subject_scores = {}

    for record in valid_history:
        subject = record[0]
        score = record[3]

        if subject not in subject_scores:
            subject_scores[subject] = []

        subject_scores[subject].append(score)

    subject_data = [["Subject", "Attempts", "Average Score"]]

    for subject, scores in subject_scores.items():
        subject_data.append([
            subject,
            str(len(scores)),
            f"{sum(scores) / len(scores):.1f}%"
        ])

    subject_table = Table(
        subject_data,
        colWidths=[180, 140, 160]
    )

    subject_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#312E81")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
        ("PADDING", (0, 0), (-1, -1), 8),
        ("ALIGN", (1, 1), (-1, -1), "CENTER")
    ]))

    elements.append(subject_table)
    elements.append(Spacer(1, 25))

    # Interview history
    elements.append(
        Paragraph("Interview History", styles["Heading2"])
    )

    history_data = [
        ["Subject", "Level", "Score", "Date"]
    ]

    for record in valid_history:
        history_data.append([
            str(record[0]),
            str(record[1]),
            f"{record[3]:.0f}%",
            str(record[4])
        ])

    history_table = Table(
        history_data,
        colWidths=[110, 110, 80, 180],
        repeatRows=1
    )

    history_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1E3A8A")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
        ("PADDING", (0, 0), (-1, -1), 7),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("FONTSIZE", (0, 0), (-1, -1), 8)
    ]))

    elements.append(history_table)

    elements.append(Spacer(1, 20))

    elements.append(
        Paragraph(
            "Generated by InterviewPrep AI",
            styles["Italic"]
        )
    )

    document.build(elements)

    buffer.seek(0)

    return buffer.getvalue()